/** Map of built-in command ID → VoiceCommand for O(1) registry lookup. */
export const BUILTIN_VOICE_COMMAND_MAP: ReadonlyMap<string, VoiceCommand> = new Map(
  BUILTIN_VOICE_COMMANDS.map((command) => [command.id, command]),
);

/** Lookup a built-in voice command by stable slug ID. */
export function getBuiltInVoiceCommand(id: string): VoiceCommand | undefined {
  return BUILTIN_VOICE_COMMAND_MAP.get(id);
}

/** Filter built-in commands available in a given mode. */
export function getBuiltInCommandsForMode(modeId: ModeId | string): VoiceCommand[] {
  return BUILTIN_VOICE_COMMANDS.filter((command) => command.allowedModeIds.includes(modeId));
}

/** Filter built-in commands by category. */
export function getBuiltInCommandsByCategory(category: VoiceCommandCategory): VoiceCommand[] {
  return BUILTIN_VOICE_COMMANDS.filter((command) => command.category === category);
}
