const BUILTIN_TIMESTAMP = '2026-01-01T00:00:00.000Z';

function cmd(
  partial: Omit<
    VoiceCommand,
    'schemaVersion' | 'enabled' | 'isBuiltIn' | 'createdAt' | 'updatedAt'
  >,
): VoiceCommand {
  return {
    schemaVersion: 1,
    enabled: true,
    isBuiltIn: true,
    createdAt: BUILTIN_TIMESTAMP,
    updatedAt: BUILTIN_TIMESTAMP,
    ...partial,
  };
}

